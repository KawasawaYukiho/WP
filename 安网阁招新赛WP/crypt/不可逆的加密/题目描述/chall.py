"""crypto-不可逆的加密 —— 附件

flag 的每个字符都被逐个加密了，加密函数如下：
    奇数字符(ASCII 为奇数)：c = (5 * n + 3) // 3
    偶数字符(ASCII 为偶数)：c = (5 * n + 2) // 4
加密结果（密文）在下面的 enc 里，一个数字对应 flag 里的一个字符。
"""


def encrypt(n):
    """输入字符的 ASCII 码 n，返回加密后的整数"""
    if n % 2 == 1:              # 奇数字符
        return (5 * n + 3) // 3
    else:                       # 偶数字符
        return (5 * n + 2) // 4


