def ror7(x):
    x = x & 0xff
    #在8bit的情况下: ROR7(x) = ROL1(x)
    return ((x >> 7) & 1) | ((x << 1) & 0xff)       #这里等价于__ROR1__(v12, 7)

route = b"ddssaassssssddddddd"
v12 = 0x42
v11 = route[0]
idx = 1
while True:
    if idx >= len(route):
        v14 = 0
    else:
        v14 = route[idx]
    v12 = v11 ^ ror7(v12)
    v11 = v14
    if v14 == 0:
        break
    idx += 1

